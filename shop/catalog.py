"""Каталог магазина и поиск по нему."""

PRODUCTS = {
    "k1": ("Чайник Ромашка Вари-1", 249000, "Чайники"),
    "k2": ("Чайник Ромашка Мини", 199000, "Чайники"),
    "t1": ("Тостер Ромашка Хруст", 279000, "Тостеры"),
    "i1": ("Утюг Ромашка Пар", 429090, "Утюги"),
    "b1": ("Блендер Ромашка Вихрь", 349000, "Блендеры"),
    "n1": ("Ёлка искусственная 150 см", 459000, "Праздник"),
    "n2": ("Гирлянда Звёздочка 10 м", 89000, "Праздник"),
    "h1": ("Щётка для одежды", 39000, "Дом"),
}


def normalize(text: str) -> str:
    """Приводим строку к виду для поиска: нижний регистр, ё как е."""
    return text.lower().replace("ё", "е")


def search(query: str) -> list[str]:
    """Артикулы товаров, в названии которых встречается запрос."""
    q = normalize(query.strip())
    return [sku for sku, (name, _, _) in PRODUCTS.items() if q in normalize(name)]


def price(sku: str) -> int:
    return PRODUCTS[sku][1]
